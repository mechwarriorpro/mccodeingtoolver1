import fs from 'node:fs'
import path from 'node:path'

/**
 * The app sets this once at startup so the scaffolder (and its tests) do not need
 * to import electron just to locate the bundled template.
 */
export function setAppPathForTemplate(appPath: string): void {
  ;(globalThis as { __mcfaAppPath?: string }).__mcfaAppPath = appPath
}

export interface ScaffoldOptions {
  targetDir: string
  modId: string
  modName: string
  group: string
  modVersion: string
  neoVersion: string
  author?: string
  license?: string
  overwrite?: boolean
}

const MOD_ID_RE = /^[a-z][a-z0-9_]{1,63}$/
const PACKAGE_RE = /^[a-z][a-z0-9_]*(\.[a-z][a-z0-9_]*)+$/
const GROUP_RE = /^[a-z][a-z0-9_]*(\.[a-z][a-z0-9_]*)*$/

export function templateRoot(): string {
  const candidates: string[] = []
  const resourcesPath = (process as unknown as { resourcesPath?: string }).resourcesPath
  if (resourcesPath) candidates.push(path.join(resourcesPath, 'template', 'neoforge-1.21.1'))
  try {
    // Only available inside Electron; the generator is also used from plain Node tests.
    const appPath = (globalThis as { __mcfaAppPath?: string }).__mcfaAppPath
    if (appPath) candidates.push(path.join(appPath, 'template', 'neoforge-1.21.1'))
  } catch {
    /* not running inside Electron (tests) */
  }
  candidates.push(path.join(process.cwd(), 'template', 'neoforge-1.21.1'))
  return candidates.find((p) => fs.existsSync(p)) ?? candidates[candidates.length - 1]
}

export function validateModId(modId: string): string | null {
  if (!MOD_ID_RE.test(modId)) return 'Mod id must be lowercase, start with a letter, and contain only a-z 0-9 _ (2-64 chars).'
  if (['minecraft', 'neoforge', 'forge', 'fml'].includes(modId)) return 'That mod id is reserved by the loader.'
  return null
}

export function validatePackage(pkg: string): string | null {
  if (!PACKAGE_RE.test(pkg)) return 'Base package must look like com.author.mymod (lowercase, dot separated).'
  if (/(^|\.)(java|javax|sun|net\.minecraft|net\.neoforged|org\.objectweb)(\.|$)/.test(pkg)) {
    return 'Base package uses a reserved namespace.'
  }
  return null
}

export function validateGroup(group: string): string | null {
  if (!GROUP_RE.test(group)) return 'Group id must look like com.author.mymod (lowercase, dot separated).'
  return null
}

function copyDir(from: string, to: string, skip: (rel: string) => boolean, base = from): void {
  for (const entry of fs.readdirSync(from, { withFileTypes: true })) {
    const src = path.join(from, entry.name)
    const dest = path.join(to, entry.name)
    // Relative to the template root, so nested skip rules work.
    const rel = path.relative(base, src).split(path.sep).join('/')
    if (skip(rel)) continue
    if (entry.isDirectory()) {
      fs.mkdirSync(dest, { recursive: true })
      copyDir(src, dest, skip, base)
    } else {
      fs.copyFileSync(src, dest)
    }
  }
}

function toPascal(modId: string): string {
  return modId
    .split(/[_\s]+/)
    .filter(Boolean)
    .map((s) => s[0].toUpperCase() + s.slice(1))
    .join('')
}

/** Package-safe java class name: "rubytools" -> "Rubytools", "ruby_tools" -> "RubyTools". */
export function classNameFor(modId: string): string {
  const name = toPascal(modId)
  return /^[0-9]/.test(name) ? `Mod${name}` : name
}

function humanName(modId: string): string {
  return modId
    .split(/[_\s]+/)
    .filter(Boolean)
    .map((s) => s[0].toUpperCase() + s.slice(1))
    .join(' ')
}

const MAIN_CLASS = (opts: ScaffoldOptions, className: string): string => `package ${opts.group};

import org.slf4j.Logger;

import com.mojang.logging.LogUtils;

import net.minecraft.core.registries.Registries;
import net.minecraft.network.chat.Component;
import net.minecraft.world.item.CreativeModeTab;
import net.minecraft.world.item.CreativeModeTabs;
import net.minecraft.world.item.Item;
import net.neoforged.bus.api.IEventBus;
import net.neoforged.bus.api.SubscribeEvent;
import net.neoforged.fml.common.Mod;
import net.neoforged.fml.config.ModConfig;
import net.neoforged.fml.ModContainer;
import net.neoforged.fml.event.lifecycle.FMLCommonSetupEvent;
import net.neoforged.neoforge.common.NeoForge;
import net.neoforged.neoforge.event.BuildCreativeModeTabContentsEvent;
import net.neoforged.neoforge.event.server.ServerStartingEvent;
import net.neoforged.neoforge.registries.DeferredHolder;
import net.neoforged.neoforge.registries.DeferredItem;
import net.neoforged.neoforge.registries.DeferredRegister;

/**
 * Main mod class for ${opts.modName}.
 *
 * Generated by MC Forge Agent. Everything in this file is a normal NeoForge 1.21.1 mod:
 * change it freely, then build and test from the app.
 */
@Mod(${className}.MODID)
public class ${className} {
    public static final String MODID = "${opts.modId}";
    public static final Logger LOGGER = LogUtils.getLogger();

    public static final DeferredRegister.Items ITEMS = DeferredRegister.createItems(MODID);
    public static final DeferredRegister<CreativeModeTab> CREATIVE_MODE_TABS =
            DeferredRegister.create(Registries.CREATIVE_MODE_TAB, MODID);

    /** A simple item: {@code ${opts.modId}:example_item}. */
    public static final DeferredItem<Item> EXAMPLE_ITEM =
            ITEMS.registerSimpleItem("example_item", new Item.Properties());

    public static final DeferredHolder<CreativeModeTab, CreativeModeTab> EXAMPLE_TAB = CREATIVE_MODE_TABS.register("example_tab",
            () -> CreativeModeTab.builder()
                    .title(Component.translatable("itemGroup.${opts.modId}"))
                    .withTabsBefore(CreativeModeTabs.COMBAT)
                    .icon(() -> EXAMPLE_ITEM.get().getDefaultInstance())
                    .displayItems((parameters, output) -> output.accept(EXAMPLE_ITEM.get()))
                    .build());

    public ${className}(IEventBus modEventBus, ModContainer modContainer) {
        modEventBus.addListener(this::commonSetup);
        modEventBus.addListener(this::addCreative);

        ITEMS.register(modEventBus);
        CREATIVE_MODE_TABS.register(modEventBus);

        NeoForge.EVENT_BUS.register(this);
        modContainer.registerConfig(ModConfig.Type.COMMON, Config.SPEC);

        LOGGER.info("{} loaded (Minecraft 1.21.1 / NeoForge)", "${opts.modName}");
    }

    private void commonSetup(final FMLCommonSetupEvent event) {
        LOGGER.info("HELLO FROM COMMON SETUP ({})", MODID);
    }

    private void addCreative(BuildCreativeModeTabContentsEvent event) {
        if (event.getTabKey() == CreativeModeTabs.BUILDING_BLOCKS) {
            event.accept(EXAMPLE_ITEM);
        }
    }

    @SubscribeEvent
    public void onServerStarting(ServerStartingEvent event) {
        LOGGER.info("HELLO from server starting");
    }
}
`

const CONFIG_CLASS = (opts: ScaffoldOptions): string => `package ${opts.group};

import net.neoforged.neoforge.common.ModConfigSpec;

/**
 * Common config for ${opts.modName}. Values are edited in config/${opts.modId}-common.toml
 * and should get lang entries (see assets/${opts.modId}/lang/en_us.json).
 */
public class Config {
    public static final ModConfigSpec.Builder BUILDER = new ModConfigSpec.Builder();
    public static final ModConfigSpec SPEC;

    public static final ModConfigSpec.BooleanValue ENABLE_FEATURE;
    public static final ModConfigSpec.IntValue EXAMPLE_NUMBER;

    static {
        BUILDER.push("general");
        ENABLE_FEATURE = BUILDER.comment("Turns the example feature on or off.").define("enable_feature", true);
        EXAMPLE_NUMBER = BUILDER.comment("An example integer value.").defineInRange("example_number", 7, 0, 1000);
        BUILDER.pop();

        SPEC = BUILDER.build();
    }

    private Config() {}
}
`

export function scaffoldProject(opts: ScaffoldOptions): { ok: true; dir: string } | { ok: false; error: string } {
  const idError = validateModId(opts.modId)
  if (idError) return { ok: false, error: idError }
  const pkgError = validatePackage(opts.group)
  if (pkgError) return { ok: false, error: pkgError }
  if (!opts.modName.trim()) return { ok: false, error: 'Mod display name is required.' }

  const dir = path.resolve(opts.targetDir)
  if (fs.existsSync(dir) && fs.readdirSync(dir).length > 0 && !opts.overwrite) {
    return { ok: false, error: `Folder is not empty: ${dir}` }
  }

  const src = templateRoot()
  if (!fs.existsSync(src)) {
    return { ok: false, error: `Bundled NeoForge 1.21.1 template missing at ${src}` }
  }

  fs.mkdirSync(dir, { recursive: true })
  copyDir(src, dir, (rel) => {
    // Drop the MDK's example sources and assets; we generate our own below.
    return rel.startsWith('src/main/java') || rel.startsWith('src/main/resources/assets')
  })

  const className = classNameFor(opts.modId) || 'ExampleMod'
  const packagePath = opts.group.split('.').join(path.sep)
  const javaDir = path.join(dir, 'src', 'main', 'java', packagePath)
  fs.mkdirSync(javaDir, { recursive: true })
  fs.writeFileSync(path.join(javaDir, `${className}.java`), MAIN_CLASS(opts, className), 'utf8')
  fs.writeFileSync(path.join(javaDir, 'Config.java'), CONFIG_CLASS(opts), 'utf8')

  const langDir = path.join(dir, 'src', 'main', 'resources', 'assets', opts.modId, 'lang')
  fs.mkdirSync(langDir, { recursive: true })
  fs.writeFileSync(
    path.join(langDir, 'en_us.json'),
    JSON.stringify(
      {
        [`item.${opts.modId}.example_item`]: humanName(opts.modId) + ' Example Item',
        [`itemGroup.${opts.modId}`]: opts.modName,
        [`${opts.modId}.configuration.title`]: opts.modName,
        [`${opts.modId}.configuration.section.general`]: 'General',
        [`${opts.modId}.configuration.enable_feature`]: 'Enable Feature',
        [`${opts.modId}.configuration.example_number`]: 'Example Number'
      },
      null,
      2
    ) + '\n',
    'utf8'
  )
  fs.writeFileSync(path.join(langDir, 'en_us.json'.replace('en_us', 'en_us')), fs.readFileSync(path.join(langDir, 'en_us.json')))

  // gradle.properties: real file used by the build
  const propsPath = path.join(dir, 'gradle.properties')
  let props = fs.readFileSync(propsPath, 'utf8')
  props = setProperty(props, 'mod_id', opts.modId)
  props = setProperty(props, 'mod_name', opts.modName)
  props = setProperty(props, 'mod_group_id', opts.group)
  props = setProperty(props, 'mod_version', opts.modVersion || '1.0.0')
  props = setProperty(props, 'mod_license', opts.license || 'All Rights Reserved')
  props = setProperty(props, 'neo_version', opts.neoVersion || '21.1.265')
  fs.writeFileSync(propsPath, props, 'utf8')

  // mod author in the metadata template
  const tomlPath = path.join(dir, 'src', 'main', 'templates', 'META-INF', 'neoforge.mods.toml')
  let toml = fs.readFileSync(tomlPath, 'utf8')
  toml = toml.replace('#authors=""', `authors="${opts.author ?? ''}"`)
  toml = toml.replace('Example mod description.', `${opts.modName} - a NeoForge 1.21.1 mod.`)
  fs.writeFileSync(tomlPath, toml, 'utf8')

  ensureAgentGitignore(dir)
  return { ok: true, dir }
}

function setProperty(text: string, key: string, value: string): string {
  const re = new RegExp(`^${key}=.*$`, 'm')
  const line = `${key}=${value}`
  return re.test(text) ? text.replace(re, line) : `${text.trimEnd()}\n${line}\n`
}

function ensureAgentGitignore(dir: string): void {
  const p = path.join(dir, '.gitignore')
  let text = fs.existsSync(p) ? fs.readFileSync(p, 'utf8') : ''
  const extra = ['run/', 'logs/', '*.log', '.agent/']
  for (const line of extra) {
    if (!text.split(/\r?\n/).includes(line)) text = text.trimEnd() + '\n' + line + '\n'
  }
  fs.writeFileSync(p, text, 'utf8')
}
